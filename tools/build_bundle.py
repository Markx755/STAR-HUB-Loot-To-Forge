#!/usr/bin/env python3
"""Build the standalone STAR HUB LocalScript bundle."""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "dist" / "star-hub.lua"
MODULES = (
    ("Shell", ROOT / "src" / "ui" / "Shell.lua"),
    ("ModuleRegistry", ROOT / "src" / "ModuleRegistry.lua"),
    ("LoaderCore", ROOT / "src" / "LoaderCore.lua"),
    ("Loader", ROOT / "src" / "Loader.lua"),
)
FORBIDDEN = re.compile(r"script\s*\.\s*Parent|loadstring|HttpGet|https?://", re.IGNORECASE)


def build_bundle() -> str:
    sections = ["-- Generated by tools/build_bundle.py; do not edit directly."]
    for name, path in MODULES:
        source = path.read_text(encoding="utf-8").rstrip()
        sections.append(f"local {name} = (function()\n{source}\nend)()")

    sections.extend(
        (
            'local player = game:GetService("Players").LocalPlayer',
            'local playerGui = player:WaitForChild("PlayerGui")',
            'if playerGui:FindFirstChild("STAR_HUB_LootToForge") then',
            '    warn("[STAR HUB] UI is already running; duplicate initialization skipped.")',
            "    return",
            "end",
            "return Loader({",
            "    LoaderCore = LoaderCore,",
            "    ModuleRegistry = ModuleRegistry,",
            "    modules = {",
            "        Shell = Shell,",
            "    },",
            "})",
        )
    )
    bundle = "\n\n".join(sections) + "\n"
    if FORBIDDEN.search(bundle):
        raise ValueError("Bundle contains a forbidden external-loading or ModuleScript reference")
    return bundle


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if the checked-in bundle differs from the current sources",
    )
    args = parser.parse_args()

    try:
        expected = build_bundle()
        if args.check:
            if not OUTPUT.is_file():
                raise FileNotFoundError(f"Bundle does not exist: {OUTPUT.relative_to(ROOT)}")
            if OUTPUT.read_text(encoding="utf-8") != expected:
                raise ValueError("Bundle is stale; run python3 tools/build_bundle.py")
            print("Bundle is up to date.")
            return 0

        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(expected, encoding="utf-8", newline="\n")
        print(f"Built {OUTPUT.relative_to(ROOT)}")
        return 0
    except (OSError, ValueError) as error:
        print(f"Build error: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
